// Release for kaiten-sushi-calc, following the delivery-workflow contract:
//   patch | minor | major  -> new semver, build +1, changelog heading, commit, tag
//   skip                   -> semver unchanged, build +1, no tag, no release page
// Usage: node scripts/release.js [patch|minor|major|skip] [--dry-run] [--push]
// Without --push nothing leaves this machine: the commit and tag stay local.
import { execSync, spawnSync } from 'node:child_process';
import fs from 'node:fs';
import readline from 'node:readline';
import { getNextVersions, getReleaseContextIssues, resolveCurrentVersion } from './release-version.js';

const ROOT = new URL('..', import.meta.url);
const path = (file) => new URL(file, ROOT);
const readJson = (file) => JSON.parse(fs.readFileSync(path(file), 'utf8'));
const sh = (cmd) => execSync(cmd, { cwd: ROOT, encoding: 'utf8' }).trim();
const CHOICES = ['patch', 'minor', 'major', 'skip'];

function run(command, args) {
  const result = spawnSync(command, args, { cwd: ROOT, stdio: 'inherit' });
  if (result.status !== 0) throw new Error(`${command} ${args.join(' ')} failed (exit ${result.status})`);
}

function askChoice() {
  const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
  return new Promise((resolve, reject) => {
    console.log('1) patch  2) minor  3) major  4) skip');
    rl.question('Choose (1-4): ', (answer) => {
      rl.close();
      const picked = CHOICES[Number.parseInt(answer, 10) - 1];
      if (picked) resolve(picked);
      else reject(new Error(`Invalid choice: ${answer}`));
    });
  });
}

async function main() {
  const args = process.argv.slice(2);
  const dryRun = args.includes('--dry-run');
  const push = args.includes('--push');
  const given = args.find((a) => !a.startsWith('--'));
  const choice = given ?? (await askChoice());
  if (!CHOICES.includes(choice)) throw new Error(`Unknown choice: ${choice} (use ${CHOICES.join(', ')})`);

  const tags = sh('git tag --list').split('\n').filter(Boolean);
  const pkg = readJson('package.json');
  const manifest = readJson('release-manifest.json');
  const current = resolveCurrentVersion(tags, pkg.version);
  const next = getNextVersions(current);
  const version = choice === 'skip' ? current : next[`next${choice[0].toUpperCase()}${choice.slice(1)}`];
  const build = manifest.build + 1;

  const branch = sh('git branch --show-current');
  const dirty = sh('git status --porcelain').length > 0;
  const issues = getReleaseContextIssues({ branch, workingTreeDirty: dirty });

  console.log('\nPreflight');
  console.log(`  current:  ${current}  (build ${manifest.build})`);
  console.log(`  patch:    ${next.nextPatch}  (build ${build})`);
  console.log(`  minor:    ${next.nextMinor}  (build ${build})`);
  console.log(`  major:    ${next.nextMajor}  (build ${build})`);
  console.log(`  skip:     ${current}  (build ${build})   <- semver unchanged`);
  console.log(`  this run: ${choice} -> ${version} (build ${build}), branch ${branch}`);
  if (issues.length > 0) {
    throw new Error(issues.join(' '));
  }
  if (dryRun) {
    console.log('\nDry run: nothing changed.');
    return;
  }

  console.log('\nGate: tests, typecheck, build');
  run('npm', ['test']);
  run('npm', ['run', 'typecheck']);
  run('npm', ['run', 'build']);

  // Candidate metadata: version in package.json, build in the manifest, and the app's version file.
  if (choice !== 'skip') {
    pkg.version = version;
    fs.writeFileSync(path('package.json'), `${JSON.stringify(pkg, null, 2)}\n`);
  }
  fs.writeFileSync(path('release-manifest.json'), `${JSON.stringify({ version, build }, null, 2)}\n`);
  fs.writeFileSync(
    path('src/config/version.ts'),
    `// Generated by scripts/release.js. Do not edit by hand.\nexport const APP_VERSION = '${version}';\nexport const APP_BUILD = ${build};\n`,
  );

  // Changelog: a tagged release gets its version heading; skip keeps the file as it is.
  if (choice !== 'skip') {
    run('git', ['cliff', '--tag', `v${version}`, '--output', 'CHANGELOG.md']);
  }

  run('git', ['add', 'package.json', 'release-manifest.json', 'src/config/version.ts', 'CHANGELOG.md']);
  run('git', ['commit', '-m', `chore(release): ${choice === 'skip' ? 'build' : 'v' + version} (build ${build})`]);

  if (choice !== 'skip') {
    run('git', ['tag', '-a', `v${version}`, '-m', `v${version}`]);
  }

  if (!push) {
    console.log('\nLocal only. To publish, run again with --push, or:');
    console.log(`  git push origin ${branch}${choice === 'skip' ? '' : ` && git push origin v${version}`}`);
    return;
  }
  if (!sh('git remote').split('\n').includes('origin')) throw new Error('No "origin" remote is configured.');
  run('git', ['push', 'origin', branch]);
  if (choice !== 'skip') {
    run('git', ['push', 'origin', `v${version}`]);
    fs.mkdirSync(path('.tmp/'), { recursive: true });
    const notes = path('.tmp/release-notes.md');
    run('git', ['cliff', '--tag', `v${version}`, '--latest', '--strip', 'header', '--output', notes.pathname]);
    run('gh', ['release', 'create', `v${version}`, '--title', `v${version}`, '--notes-file', notes.pathname]);
  }
}

main().catch((err) => {
  console.error(`\n❌ ${err.message}`);
  process.exit(1);
});
